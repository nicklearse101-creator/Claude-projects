"""Put the photo-measured front end into the blocky model: bumper (ribs, plate recess, grey chin lip), lamp
panel, grille surround + insert + groove, headlamps (glass, housing, chrome reflector) and the wrap-round
indicators.

These parts are not modelled here - they are generated by `tools/front_end.py` from the multi-view
triangulations in `tools/photomatch/ba_result.json` plus the c20 / cCF / c22 / cS overlays (see the
2026-10-12 entries in docs/DECISIONS.md), which is the most accurate front-end data the project has. The
Meshy shell is NOT the ruler here: its nose is the weakest part of the generated mesh, reading ~60 mm low
and ~80 mm short at the bonnet's leading edge.

The JSON is in the photo frame (ground = loaded tyre contact), so every z gets DZ to sit on the model's
unloaded tyres. The blocky front parts it replaces are deleted.

  python tools/front_end.py blender/data/front_end.json          (regenerate, needs the project .venv)
  blender -b blender/nova_proc.blend --python tools/gen/add_front_end.py -- out.blend
"""
import json
import math
import os
import sys

import bpy

args = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
OUT = args[0] if args and not args[0].startswith("--") else None
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(ROOT, "blender", "data", "front_end.json")

DZ = 0.0193             # photo frame -> model frame; tools/photomatch/body_profile.json
REPLACES = ("Bumper_Front_GTE", "Housing_Grille", "Housing_Headlight_Left", "Housing_Headlight_Right")
TRIM = ("Hood", "Fender_Front_Left", "Fender_Front_Right")   # old blocky nose skin ahead of the bonnet edge
EDGE_Y0, EDGE_A = -1.755, 0.151      # measured bonnet front edge (rebuild_bonnet.py); everything in front of
EDGE_MARGIN = 0.004                  # it is now carried by the lamp panel, grille and bumper
SHELLS = {"BUMPER_F": 0.003, "BUMPER_F_LIP": 0.003}     # sheet parts get real thickness, inwards
MATS = {                                                # name: (rgba, metallic, roughness)
    # body colour matches the clay the rest of the block-out is rendered in, so shape is judged, not paint
    "paint_gunmetal": ((0.62, 0.63, 0.64, 1), 0.0, 0.42),
    "trim_grey": ((0.17, 0.17, 0.18, 1), 0.0, 0.55),
    "trim_black": ((0.02, 0.02, 0.02, 1), 0.0, 0.60),
    "bumper_stripe": ((0.55, 0.03, 0.03, 1), 0.0, 0.40),
    "plate_front": ((0.86, 0.86, 0.83, 1), 0.0, 0.35),
    "grille_black": ((0.015, 0.015, 0.015, 1), 0.0, 0.60),
    "panel_gap": ((0.01, 0.01, 0.01, 1), 0.0, 0.80),
    "chrome": ((0.80, 0.80, 0.80, 1), 1.0, 0.08),
    "lamp_clear": ((0.85, 0.86, 0.88, 1), 0.0, 0.05),
    "lamp_amber": ((0.80, 0.35, 0.02, 1), 0.0, 0.10),
}


def material(name):
    rgba, met, rough = MATS.get(name, ((0.5, 0.5, 0.5, 1), 0.0, 0.5))
    m = bpy.data.materials.get(name)        # refresh an existing one too, so re-runs pick up colour changes
    if m is None:
        m = bpy.data.materials.new(name)
    m.use_nodes = True
    b = next(n for n in m.node_tree.nodes if n.type == "BSDF_PRINCIPLED")
    b.inputs["Base Color"].default_value = rgba
    b.inputs["Metallic"].default_value = met
    b.inputs["Roughness"].default_value = rough
    m.diffuse_color = rgba
    return m


def sharp_by_angle(me, deg):
    """Blender 5.x renamed this; the old name silently missing is what smooth-shaded every hard corner once."""
    for name in ("set_sharp_from_angle", "set_sharpness_by_angle"):
        fn = getattr(me, name, None)
        if fn:
            fn(angle=math.radians(deg))
            return
    raise RuntimeError("no sharp-by-angle API in this Blender")


coll = bpy.data.collections.get("FRONT")
if coll is None:
    coll = bpy.data.collections.new("FRONT")
    bpy.context.scene.collection.children.link(coll)

for name in REPLACES:
    ob = bpy.data.objects.get(name)
    if ob is not None:
        print("replaced blocky part: %s (%d faces)" % (name, len(ob.data.polygons)))
        bpy.data.objects.remove(ob, do_unlink=True)

import bmesh

for name in TRIM:
    ob = bpy.data.objects.get(name)
    if ob is None:
        continue
    bm = bmesh.new()
    bm.from_mesh(ob.data)
    kill = [f for f in bm.faces
            if f.calc_center_median().y < EDGE_Y0 + EDGE_A * abs(f.calc_center_median().x) + EDGE_MARGIN]
    if kill:
        print("%s: %d old nose faces removed" % (name, len(kill)))
        bmesh.ops.delete(bm, geom=kill, context="FACES")
    bm.to_mesh(ob.data)
    bm.free()
    ob.data.update()

data = json.load(open(DATA))
total = 0
for name, p in data.items():
    old = bpy.data.objects.get(name)
    if old is not None:
        bpy.data.objects.remove(old, do_unlink=True)
    me = bpy.data.meshes.new(name)
    me.from_pydata([(x, y, z + DZ) for x, y, z in p["verts"]], [], p["faces"])
    for mname in p["mats"]:
        me.materials.append(material(mname))
    me.polygons.foreach_set("material_index", p["mat_idx"])
    me.validate()
    me.update()
    me.polygons.foreach_set("use_smooth", [True] * len(me.polygons))
    sharp_by_angle(me, 40)
    ob = bpy.data.objects.new(name, me)
    coll.objects.link(ob)
    if name in SHELLS:
        sm = ob.modifiers.new("Thickness", "SOLIDIFY")
        sm.thickness = SHELLS[name]
        sm.offset = -1.0
        sm.use_even_offset = False
        sm.use_rim = True
    total += len(me.polygons)
print("front end: %d parts, %d faces" % (len(data), total))

if OUT:
    bpy.ops.wm.save_as_mainfile(filepath=bpy.path.abspath(OUT))
    print("saved", OUT)
