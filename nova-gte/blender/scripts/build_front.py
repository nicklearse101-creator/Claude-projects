"""Load the generated parts (front_end / side_parts / rear_end JSON). Front end parts (bumper + lip, plate, lamp panel, grille surround + insert, headlamps, indicators)
from blender/data/front_end.json (generated by tools/front_end.py, BA/photo frame) into the FRONT collection,
lifted by DZ onto the model's unloaded tyres. Runs inside Blender."""
import json
import math
import os
import sys

import bpy

ROOT = r"D:\Claude\vauxhall_nova_gte_1989"
DATA = [os.path.join(ROOT, "blender", "data", n) for n in ("front_end.json", "side_parts.json", "rear_end.json")]
sys.path.insert(0, os.path.join(ROOT, "blender", "scripts"))
import body_geom as g  # noqa: E402

MATS = {  # name: (rgba, ac preset, metallic, roughness)
    "paint_gunmetal": None,
    "trim_grey": None, "trim_black": None,
    "bumper_stripe": ((0.55, 0.03, 0.03, 1), "trim", 0.0, 0.4),
    "plate_front": ((0.86, 0.86, 0.83, 1), "trim", 0.0, 0.35),
    "grille_black": ((0.015, 0.015, 0.015, 1), "trim", 0.0, 0.6),
    "chrome": ((0.8, 0.8, 0.8, 1), "chrome", 1.0, 0.08),
    "lamp_clear": None, "lamp_amber": None,
}


SHELLS = {"BUMPER_F": 0.003, "BUMPER_F_LIP": 0.003, "BUMPER_R": 0.003, "BUMPER_R_VALANCE": 0.003}



def sharp_by_angle(me, deg):
    """Hard edges above deg (Blender 5.x: set_sharp_from_angle; 4.1-4.x: set_sharpness_by_angle)."""
    for name in ("set_sharp_from_angle", "set_sharpness_by_angle"):
        fn_ = getattr(me, name, None)
        if fn_:
            fn_(angle=math.radians(deg))
            return True
    raise RuntimeError("no sharp-by-angle API in this Blender")

def material(name):
    m = bpy.data.materials.get(name)
    if m is None:
        rgba, preset, met, rough = MATS.get(name) or ((0.5, 0.5, 0.5, 1), "trim", 0.0, 0.5)
        m = bpy.data.materials.new(name); m.use_nodes = True
        b = next(n for n in m.node_tree.nodes if n.type == "BSDF_PRINCIPLED")
        b.inputs["Base Color"].default_value = rgba; b.inputs["Metallic"].default_value = met
        b.inputs["Roughness"].default_value = rough; m.diffuse_color = rgba
        m["ac_preset"] = preset; m["ac_shader"] = "ksPerPixelMultiMap"
    return m


def build():
    out = {}
    for path in DATA:
        if not os.path.exists(path):
            continue
        cname = os.path.basename(path).split("_")[0].upper()          # FRONT / SIDE / REAR
        coll = bpy.data.collections.get(cname)
        if coll is None:
            coll = bpy.data.collections.new(cname); bpy.context.scene.collection.children.link(coll)
        out.update(load(json.load(open(path)), coll))
    return out


def load(data, coll):
    out = {}
    for name, p in data.items():
        old = bpy.data.objects.get(name)
        if old is not None:
            me_old = old.data; bpy.data.objects.remove(old)
            if me_old and me_old.users == 0:
                bpy.data.meshes.remove(me_old)
        me = bpy.data.meshes.new(name)
        verts = [(x, y, z + g.DZ) for x, y, z in p["verts"]]
        me.from_pydata(verts, [], p["faces"])
        for mname in p["mats"]:
            me.materials.append(material(mname))
        me.polygons.foreach_set("material_index", p["mat_idx"])
        me.validate(); me.update()
        for poly in me.polygons:
            poly.use_smooth = True
        sharp_by_angle(me, 40)
        ob = bpy.data.objects.new(name, me); coll.objects.link(ob)
        if name in SHELLS:                       # sheet parts get real thickness (inwards)
            sm = ob.modifiers.new("Thickness", "SOLIDIFY"); sm.thickness = SHELLS[name]; sm.offset = -1.0
            sm.use_even_offset = False; sm.use_rim = True
        out[name] = len(me.polygons)
    return out


if __name__ == "__main__":
    print(build())
